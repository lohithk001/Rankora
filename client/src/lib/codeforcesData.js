// Helper to convert Codeforces coder to Rankora leaderboard row format
export function mapCodeforcesToLeaderboardRow(cf) {
  const flag = cf.country ? (COUNTRY_FLAGS[cf.country] || "🌐") : "🌐";
  // Convert CF rating (2548 - 3670) to Rankora composite signal score (910 - 998)
  const score = Math.round(900 + ((cf.rating - 2500) / (3700 - 2500)) * 98);
  const displayName = cf.realName ? `${cf.realName} (${cf.handle})` : cf.handle;

  return {
    rank: cf.rank,
    username: cf.handle,
    name: displayName,
    country: cf.country || "Global",
    flag,
    score,
    rating: cf.rating,
    maxRating: cf.maxRating,
    title: cf.title,
    organization: cf.organization || "Independent",
    change: cf.rank <= 3 ? "+0" : (cf.rank % 2 === 0 ? `+${(cf.rank % 5) + 1}` : `-${(cf.rank % 3) + 1}`),
    isPositive: cf.rank % 2 === 0,
    category: "Algorithms",
    avatar: cf.avatar && !cf.avatar.includes('no-avatar') 
      ? cf.avatar 
      : `https://api.dicebear.com/7.x/identicon/svg?seed=${cf.handle}`,
    profileUrl: cf.profile
  };
}

